"""Build the Proscenium extension zip for the current platform, with its runtime wheels and compiled core.

    uv run python tools/build_extension.py [--source-dir DIR] [--output-dir DIR] [--check]

--check (build(..., sync=False)) skips steps 2 to 4's writes: the source dir is
only read, and the build fails if its wheels, generated block, or compiled core
are out of date.

Steps:
1. Export the runtime dependencies (never the dev group) from uv.lock as a
   pylock and select each package's wheel for this machine. The uv environment
   runs Python 3.13 like Blender 5.2, so its tags match Blender's.
2. Sync <source>/wheels/ (generated, gitignored) to that set: a wheel already
   present with the locked sha256 is kept, missing ones are downloaded and
   hash-checked, stale ones are removed.
3. Rewrite the manifest's generated block (between BEGIN and END, above the
   first table) with the matching `wheels` key.
4. Build the compiled core from <source>/core/ (tools/native_build.py) and copy
   its module (generated, gitignored) into that package, unless the module there
   is current: build/core/build.json records this platform, the locked Blender
   release, the hash of the sources and build tools it was built from, and the
   module's own hash. CI's Linux tests use a module built on Blender's glibc
   floor this way.
5. Copy the source dir to a temporary dir and add the build's keys to the copy's
   generated block, so the checked-in manifest stays the same on every platform
   and release: `platforms` (this platform) and `blender_version_max` (the next
   minor after the locked release, since the module binds to that release's exact
   USD build), then validate and build the copy with the extension CLI shipped in
   the bpy wheel, so no Blender binary is needed
   (docs/feasibility/runtime-record.md#packaging).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
from pathlib import Path
from typing import Any

from packaging.pylock import PackageWheel, Pylock

from blender_deps import current_platform
from blender_paths import wheel_extension_cli
from blender_release import blender_tag, blender_version
from native_build import build_module

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "# --- begin generated by tools/build_extension.py ---\n"
END = "# --- end generated ---\n"
GENERATED_KEYS = ("wheels", "platforms", "blender_version_max")
CORE = "_core"  # proscenium.core._core
CORE_BUILD = ROOT / "build" / "core"
# What the core is built from: its sources (the manifest's [build] patterns keep them out of the zip),
# and the build tools.
CORE_SOURCES = ("*.cpp", "*.h", "CMakeLists.txt")
BUILD_TOOLS = (Path(__file__).with_name("native_build.py"), Path(__file__).with_name("blender_deps.py"))


def runtime_wheels() -> list[PackageWheel]:
    """This machine's wheel for every runtime package locked in uv.lock."""
    out = subprocess.run(
        ["uv", "export", "--locked", "--no-dev", "--no-emit-project", "--format", "pylock.toml"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    lock = tomllib.loads(out)
    lock.setdefault("packages", [])  # uv omits the key when there are no runtime dependencies
    wheels = []
    for package, dist in Pylock.from_dict(lock).select():
        if not isinstance(dist, PackageWheel):
            raise SystemExit(f"{package.name}: uv.lock has no wheel for this platform")
        wheels.append(dist)
    return sorted(wheels, key=lambda w: w.filename)


def sync_wheels(wheels: list[PackageWheel], dest: Path, *, write: bool = True) -> list[Path]:
    """Make dest hold exactly these wheels, downloading only missing or mismatched ones.

    With write=False nothing is changed: it fails unless dest already matches.
    """
    wanted = {w.filename: w.hashes["sha256"] for w in wheels}
    stale = [p for p in dest.glob("*.whl") if wanted.get(p.name) != hashlib.sha256(p.read_bytes()).hexdigest()]
    missing = [w for w in wheels if not (dest / w.filename).exists() or dest / w.filename in stale]
    if not write:
        if stale or missing:
            names = sorted({p.name for p in stale} | {w.filename for w in missing})
            raise SystemExit(f"{dest}: wheels differ from uv.lock ({names}); run tools/build_extension.py")
        return [dest / w.filename for w in wheels]
    for path in stale:
        path.unlink()
    for wheel in missing:
        path = dest / wheel.filename
        dest.mkdir(exist_ok=True)
        if wheel.url is None:
            raise SystemExit(f"{wheel.filename}: no download URL in uv.lock")
        with urllib.request.urlopen(wheel.url) as response:
            data = response.read()
        if hashlib.sha256(data).hexdigest() != wheel.hashes["sha256"]:
            raise SystemExit(f"{wheel.filename}: sha256 does not match uv.lock")
        path.write_bytes(data)
    return [dest / w.filename for w in wheels]


def sync_manifest(manifest: Path, wheels: list[Path], *, write: bool = True) -> bool:
    """Rewrite the generated block; returns whether the file changed.

    With write=False nothing is changed: it fails unless the block is already current.
    """
    text = manifest.read_text(encoding="utf-8")
    head, begin, rest = text.partition(BEGIN)
    _, end, tail = rest.partition(END)
    if not (begin and end):
        raise SystemExit(f"{manifest}: missing the generated-block markers {BEGIN.strip()!r} / {END.strip()!r}")
    hand_written = tomllib.loads(head + tail)
    for key in GENERATED_KEYS:
        if key in hand_written:
            raise SystemExit(f"{manifest}: {key!r} is generated; remove it outside the markers")

    block = ""
    if wheels:
        # json.dumps of a list of plain strings is a valid TOML array.
        block = f"wheels = {json.dumps([f'./wheels/{w.name}' for w in wheels])}\n"
    new = head + BEGIN + block + END + tail
    if tomllib.loads(new).get("wheels", []) != [f"./wheels/{w.name}" for w in wheels]:
        raise SystemExit(f"{manifest}: the generated block must be above the first table")
    if new != text:
        if not write:
            raise SystemExit(
                f"{manifest}: the generated block is out of date with uv.lock; run tools/build_extension.py"
            )
        manifest.write_text(new, encoding="utf-8")
    return new != text


def sync_core(core_dir: Path, *, write: bool = True) -> Path:
    """Build the compiled core into core_dir unless the module there is current; returns the module.

    With write=False nothing is built: it fails unless the module is already current.
    """
    record = CORE_BUILD / "build.json"
    inputs = _core_inputs(core_dir)
    current = _current_core(core_dir, record, inputs)
    if current is not None:
        return current
    if not write:
        raise SystemExit(f"{core_dir}: the compiled core is missing or out of date; run tools/build_extension.py")
    built = build_module(core_dir, CORE_BUILD, CORE)
    for stale in _core_modules(core_dir):
        stale.unlink()
    module = Path(shutil.copy2(built.module, core_dir / built.module.name))
    build = {k: v for k, v in built.manifest.items() if k not in {"imports", "linkage"}}
    record.write_text(json.dumps({**inputs, "module_sha256": _sha256(module), "build": build}, indent=2) + "\n")
    print(f"built {module}")
    return module


def _core_inputs(core_dir: Path) -> dict[str, Any]:
    sources = hashlib.sha256()
    files = {p for pattern in CORE_SOURCES for p in core_dir.rglob(pattern)}
    for path in sorted(files, key=lambda p: p.relative_to(core_dir).as_posix()):
        sources.update(path.relative_to(core_dir).as_posix().encode() + b"\0" + path.read_bytes() + b"\0")
    for path in BUILD_TOOLS:
        sources.update(path.name.encode() + b"\0" + path.read_bytes() + b"\0")
    return {"platform": str(current_platform()), "blender_tag": blender_tag(), "sources_sha256": sources.hexdigest()}


def _current_core(core_dir: Path, record: Path, inputs: dict[str, Any]) -> Path | None:
    """The module in core_dir, if the build record matches inputs and the module itself."""
    if not record.is_file():
        return None
    recorded = json.loads(record.read_text(encoding="utf-8"))
    modules = _core_modules(core_dir)
    if any(recorded.get(k) != v for k, v in inputs.items()) or len(modules) != 1:
        return None
    return modules[0] if _sha256(modules[0]) == recorded.get("module_sha256") else None


def _core_modules(core_dir: Path) -> list[Path]:
    return sorted(p for p in core_dir.glob(f"{CORE}.*") if p.suffix in {".so", ".pyd"})


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _add_build_keys(manifest: Path, platform: str, release: str) -> None:
    """Limit a copy of the manifest to this platform and the locked release's minor version (e.g. 5.2.x)."""
    text = manifest.read_text(encoding="utf-8")
    major, minor = release.split(".")[:2]
    supported = f"{major}.{minor}."
    if not tomllib.loads(text)["blender_version_min"].startswith(supported):
        raise SystemExit(f"{manifest}: blender_version_min must be in {supported}x, the locked Blender release's minor")
    head, end, tail = text.partition(END)
    if not end:
        raise SystemExit(f"{manifest}: missing the generated-block end marker {END.strip()!r}")
    # blender_version_max is the first version that is not supported.
    keys = f'platforms = {json.dumps([platform])}\nblender_version_max = "{major}.{int(minor) + 1}.0"\n'
    manifest.write_text(f"{head}{keys}{end}{tail}", encoding="utf-8")


def _cli(*args: str) -> None:
    cli = wheel_extension_cli()
    if cli is None:
        raise SystemExit("bpy wheel not found: run from the uv environment (uv sync)")
    proc = subprocess.run([sys.executable, str(cli), *args], capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise SystemExit(f"extension {args[0]} failed ({proc.returncode}):\n{proc.stdout}{proc.stderr}")


def build(source_dir: Path, output_dir: Path, *, sync: bool = True) -> Path:
    """Sync wheels into the manifest, build the core, validate, and build; returns the archive path.

    With sync=False the source dir is only read: the build fails unless its wheels
    and generated block already match uv.lock and its compiled core is current.
    Safe to run concurrently (tests).
    """
    wheels = sync_wheels(runtime_wheels(), source_dir / "wheels", write=sync)
    if sync_manifest(source_dir / "blender_manifest.toml", wheels, write=sync):
        print("updated blender_manifest.toml wheels from uv.lock")
    sync_core(source_dir / "core", write=sync)
    manifest = tomllib.loads((source_dir / "blender_manifest.toml").read_text(encoding="utf-8"))
    archive = output_dir / f"{manifest['id']}-{manifest['version']}.zip"

    with tempfile.TemporaryDirectory(prefix="proscenium-build-") as tmp:
        staged = Path(tmp) / source_dir.name
        shutil.copytree(source_dir, staged, ignore=shutil.ignore_patterns("__pycache__"))
        _add_build_keys(staged / "blender_manifest.toml", str(current_platform()), blender_version())
        _cli("validate", str(staged))
        output_dir.mkdir(parents=True, exist_ok=True)  # the CLI does not create it
        archive.unlink(missing_ok=True)
        _cli("build", "--source-dir", str(staged), "--output-dir", str(output_dir))
    _cli("validate", str(archive))
    return archive


def main() -> int:
    """Build the extension zip, or with --check only verify the source dir; the exit status."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source-dir", type=Path, default=ROOT / "src" / "proscenium")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "dist")
    parser.add_argument(
        "--check",
        action="store_true",
        help="never write to the source dir; fail if its wheels, manifest, or compiled core are out of date",
    )
    args = parser.parse_args()
    print(f"built {build(args.source_dir, args.output_dir, sync=not args.check)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
