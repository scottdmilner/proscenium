"""Append bpy's bundled site-packages to sys.path.

The bpy wheel ships third-party packages (pxr, MaterialX, OpenImageIO,
PyOpenColorIO, openvdb, ...) in an internal site-packages directory that is not
on sys.path. This module is loaded at interpreter startup by
bpy_site_packages.pth. bpy itself is not imported, only located, so startup
stays cheap.

The module name must differ from the .pth stem. Pylance's editable-install
support imports the module named after the .pth and maps that module's
directory (here, site-packages itself) into a virtual overlay, which hides all
of site-packages from import resolution.
"""

import importlib.util
import os
import sys
from pathlib import Path


def _bundled_site_packages() -> list[Path]:
    spec = importlib.util.find_spec("bpy")
    if spec is None or spec.origin is None:
        return []
    root = Path(spec.origin).parent
    found = []
    if os.name == "posix":  # macOS/Linux
        found = root.glob("*/python/lib/python*/site-packages")
    elif os.name == "nt":  # Windows
        found = root.glob("*/python/lib/site-packages")
        # Windows does not search PATH for DLL dependencies. pxr's extension modules need the
        # USD and TBB DLLs next to the bpy package, which importing bpy would otherwise register.
        os.add_dll_directory(str(root))
    return sorted(found)


for _path in _bundled_site_packages():
    if str(_path) not in sys.path:
        sys.path.append(str(_path))
